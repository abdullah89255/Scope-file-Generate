#!/usr/bin/env python3
"""mkscope.py — generate a h1hunter scope.yaml from a list of domains.

Examples
--------
    # From arguments:
    python3 mkscope.py --program acme --domain acme.test --domain api.acme.test

    # From a file (one per line, # comments allowed):
    python3 mkscope.py --program acme --domains-file data/domains.txt

    # Wildcards are expanded automatically: acme.test becomes both
    # acme.test and *.acme.test unless you pass --no-wildcard.

    # Exclusions:
    python3 mkscope.py --program acme --domain acme.test \
        --exclude admin.acme.test --exclude billing.acme.test

    # Overwrite an existing scope.yaml:
    python3 mkscope.py --program acme --domain acme.test --force

    # Write to a custom path:
    python3 mkscope.py --program acme --domain acme.test \
        --output config/scope-acme.yaml

By default the scope is written with:
    policy_reviewed: false
    active_checks:   false

You must review the program policy and flip both to true yourself before
running any active command. This script deliberately refuses to flip them.
"""
from __future__ import annotations

import argparse
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

# ---------------------------------------------------------------------------


def is_ip_literal(value: str) -> bool:
    """Return True if value looks like an IPv4/IPv6 literal or CIDR block."""
    import ipaddress
    v = value.strip().strip("[]")
    if "/" in v:
        try:
            ipaddress.ip_network(v, strict=False)
            return True
        except ValueError:
            return False
    try:
        ipaddress.ip_address(v)
        return True
    except ValueError:
        return False


def normalize_domain(value: str) -> str:
    """Strip scheme, path, port, trailing dot, and lower-case the host."""
    v = value.strip()
    if not v:
        raise ValueError("empty entry")
    if v.startswith("*."):
        v = "*." + v[2:].lower().rstrip(".")
        return v
    if "://" in v:
        from urllib.parse import urlsplit
        parts = urlsplit(v)
        host = parts.hostname
        if not host:
            raise ValueError(f"could not extract host from {value!r}")
        v = host
    if "/" in v:
        v = v.split("/", 1)[0]
    if ":" in v and not v.startswith("["):
        v = v.split(":", 1)[0]
    v = v.strip().rstrip(".").lower()
    if not v:
        raise ValueError(f"empty after normalization: {value!r}")
    return v


def read_domains_file(path: Path) -> list[str]:
    if not path.exists():
        raise SystemExit(f"domains file not found: {path}")
    if not path.is_file():
        raise SystemExit(f"domains path is not a file: {path}")
    entries: list[str] = []
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        stripped = line.split("#", 1)[0].strip()
        if not stripped:
            continue
        entries.append(stripped)
    return entries


def dedupe_preserve(seq: list[str]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for item in seq:
        if item not in seen:
            seen.add(item)
            out.append(item)
    return out


# ---------------------------------------------------------------------------


def build_yaml(
    program: str,
    allowed: list[str],
    excluded: list[str],
    *,
    policy_url: str,
    authorized_by: str,
    passive_recon: bool,
    active_checks: bool,
    max_concurrency: int,
    requests_per_second: float,
    timeout_seconds: int,
    max_requests: int,
    max_response_bytes: int,
    allow_private_networks: bool,
) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d")

    def block(items: list[str], indent: int = 2) -> str:
        if not items:
            return "[]"
        pad = " " * indent
        return "\n".join(f'{pad}- "{item}"' for item in items)

    lines: list[str] = []
    lines.append("# h1hunter program scope")
    lines.append(f"# Generated by mkscope.py on {now}")
    lines.append("#")
    lines.append("# REVIEW THIS FILE CAREFULLY.")
    lines.append("# 1. Confirm every 'allowed' entry appears on the program's scope page.")
    lines.append("# 2. Add any exclusions the policy calls out.")
    lines.append("# 3. Read the policy, then set policy_reviewed: true below.")
    lines.append("# 4. Set active_checks: true only when you are ready to send traffic.")
    lines.append("")
    lines.append("program:")
    lines.append(f'  name: "{program}"')
    lines.append("  policy_reviewed: false")
    lines.append(f'  policy_url: "{policy_url}"')
    lines.append(f'  authorized_by: "{authorized_by}"')
    lines.append("")
    lines.append("allowed:")
    lines.append(block(allowed))
    lines.append("")
    lines.append("excluded:")
    if excluded:
        lines.append(block(excluded))
    else:
        lines.append("  []")
    lines.append("")
    lines.append("settings:")
    lines.append(f"  passive_recon: {str(passive_recon).lower()}")
    lines.append(f"  active_checks: {str(active_checks).lower()}")
    lines.append(f"  max_concurrency: {max_concurrency}")
    lines.append(f"  requests_per_second: {requests_per_second}")
    lines.append(f"  timeout_seconds: {timeout_seconds}")
    lines.append(f"  max_requests: {max_requests}")
    lines.append(f"  max_response_bytes: {max_response_bytes}")
    lines.append(f"  allow_private_networks: {str(allow_private_networks).lower()}")
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        prog="mkscope.py",
        description=(
            "Generate a h1hunter scope.yaml from one or more domains, IPs, "
            "or CIDR blocks. Writes a conservative file by default: "
            "policy_reviewed and active_checks are always false."
        ),
    )
    p.add_argument("--program", required=True, help="Program name (e.g. acme).")
    p.add_argument(
        "--domain", action="append", default=[], metavar="HOST",
        help="Repeatable. A domain, URL, IP, or CIDR block.",
    )
    p.add_argument(
        "--domains-file", type=Path, default=None,
        help="Read additional entries from this file (one per line, # comments allowed).",
    )
    p.add_argument(
        "--exclude", action="append", default=[], metavar="HOST",
        help="Repeatable. Excluded host, URL, IP, or CIDR block.",
    )
    p.add_argument(
        "--no-wildcard", action="store_true",
        help="Do NOT expand a bare domain into a matching *.domain entry.",
    )
    p.add_argument(
        "--output", type=Path, default=Path("config/scope.yaml"),
        help="Where to write the scope file (default: config/scope.yaml).",
    )
    p.add_argument(
        "--force", action="store_true",
        help="Overwrite the output file if it already exists.",
    )
    p.add_argument("--policy-url", default="", help="Program policy URL.")
    p.add_argument("--authorized-by", default="", help="Your handle or email.")

    # Conservative defaults; overridable but you must ask for the change.
    p.add_argument("--max-concurrency", type=int, default=2)
    p.add_argument("--requests-per-second", type=float, default=1.0)
    p.add_argument("--timeout-seconds", type=int, default=10)
    p.add_argument("--max-requests", type=int, default=200)
    p.add_argument("--max-response-bytes", type=int, default=524288)
    p.add_argument(
        "--allow-private-networks", action="store_true",
        help=(
            "Opt in to non-globally-routable destinations. Metadata and "
            "loopback remain blocked regardless."
        ),
    )
    return p.parse_args(argv)


# ---------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)

    raw_allowed: list[str] = list(args.domain)
    if args.domains_file:
        raw_allowed.extend(read_domains_file(args.domains_file))

    if not raw_allowed:
        print(
            "error: supply at least one --domain or --domains-file entry",
            file=sys.stderr,
        )
        return 2

    allowed: list[str] = []
    for item in raw_allowed:
        try:
            allowed.append(normalize_domain(item))
        except ValueError as exc:
            print(f"error: {item!r}: {exc}", file=sys.stderr)
            return 2

    # Expand bare domains to include wildcards, unless the user opted out
    # or the entry is an IP/CIDR.
    expanded: list[str] = []
    for entry in allowed:
        expanded.append(entry)
        if args.no_wildcard:
            continue
        if entry.startswith("*."):
            continue
        if is_ip_literal(entry):
            continue
        if "." not in entry:
            continue
        # Add a wildcard for the registrable-ish parent. This is a heuristic
        # (two labels), consistent with the toolkit's derive_domain().
        labels = entry.split(".")
        if len(labels) >= 2:
            parent = ".".join(labels[-2:])
            wildcard = f"*.{parent}"
            if wildcard not in expanded:
                expanded.append(wildcard)

    expanded = dedupe_preserve(expanded)

    excluded: list[str] = []
    for item in args.exclude:
        try:
            excluded.append(normalize_domain(item))
        except ValueError as exc:
            print(f"error (exclude): {item!r}: {exc}", file=sys.stderr)
            return 2
    excluded = dedupe_preserve(excluded)

    if args.output.exists() and not args.force:
        print(
            f"error: {args.output} already exists; pass --force to overwrite",
            file=sys.stderr,
        )
        return 2

    text = build_yaml(
        program=args.program,
        allowed=expanded,
        excluded=excluded,
        policy_url=args.policy_url or f"https://hackerone.com/{args.program}",
        authorized_by=args.authorized_by or "you@example.test",
        passive_recon=True,
        active_checks=False,               # always off; user must opt in
        max_concurrency=args.max_concurrency,
        requests_per_second=args.requests_per_second,
        timeout_seconds=args.timeout_seconds,
        max_requests=args.max_requests,
        max_response_bytes=args.max_response_bytes,
        allow_private_networks=args.allow_private_networks,
    )

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")

    print(f"Wrote {args.output}")
    print(f"  program:  {args.program}")
    print(f"  allowed:  {len(expanded)} entries")
    for entry in expanded:
        print(f"    - {entry}")
    if excluded:
        print(f"  excluded: {len(excluded)} entries")
        for entry in excluded:
            print(f"    - {entry}")
    else:
        print("  excluded: (none)")
    print()
    print("Next steps:")
    print(f"  1. Open {args.output} and verify every entry against the program")
    print("     policy on HackerOne.")
    print("  2. Set policy_reviewed: true only after reading the policy.")
    print("  3. Set active_checks: true only when ready to send traffic.")
    print(f"  4. Validate:  h1hunter scope validate --file {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
